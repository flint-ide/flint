// Command wuicss generates ui/css/wunderui.css: WunderUI's design
// tokens plus the Tailwind utilities its components (@wunderui/react) use,
// compiled once with the standalone Tailwind CLI so the app build needs no
// Tailwind and no Node toolchain.
//
// Run it after changing the @wunderui/react version (from the repository root):
//
//	go run ./cmd/wuicss
//
// It downloads the pinned Tailwind CLI into .task/bin (checked against its
// SHA-256), compiles ui/css/wunderui.input.css, renames WunderUI's
// variables that would clash with Flint's theme (see renames) and writes the result.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"time"
)

const (
	tailwindVersion = "4.3.5"
	// Paths from the repository root. The input imports the package installed
	// in frontend/node_modules.
	inputFile  = "ui/css/wunderui.input.css"
	outputFile = "ui/css/wunderui.css"
)

// Release checksums from github.com/tailwindlabs/tailwindcss/releases/download/v4.3.5/sha256sums.txt.
var tailwindSHA256 = map[string]string{
	"macos-arm64": "f3f4f5d1727e2b693b8f1c9a1492b5dd87008c86ea286bee1589cb458e6235fc",
	"macos-x64":   "a63702686a3ed048b3135d84a73be49ea9d47f880c9b20e54b3ef60934ad8cdf",
	"linux-arm64": "ffcd0d21dbd7c605dc12743ff0c0b47debc963c86b399674084c1c8f2c96ecad",
	"linux-x64":   "e47695cee3f0d90623a91f3939b08bdee610eb5ad99340adff9d4145b284d6cc",
}

// WunderUI variables whose names Flint's style.css already uses for its own theme
// (--accent is Flint's amber, --border every divider). They get a prefix in the
// generated file so loading WunderUI never repaints the rest of Flint.
var renames = []string{"--accent", "--border"}

const header = "/* GENERATED by `go run ./cmd/wuicss` from wunderui.input.css (WunderUI Free, MIT; Tailwind CSS, MIT). Do not edit. */\n"

func main() {
	tailwind := flag.String("tailwind", "", "path to a Tailwind CLI binary (default: download the pinned version into .task/bin)")
	flag.Parse()
	if err := run(*tailwind); err != nil {
		fmt.Fprintln(os.Stderr, "wuicss:", err)
		os.Exit(1)
	}
}

func run(tailwind string) error {
	if tailwind == "" {
		var err error
		if tailwind, err = ensureTailwind(); err != nil {
			return err
		}
	}
	tmp, err := os.CreateTemp("", "wunderui-*.css")
	if err != nil {
		return err
	}
	tmp.Close()
	defer os.Remove(tmp.Name())

	cmd := exec.Command(tailwind, "--input", inputFile, "--output", tmp.Name())
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("tailwind: %w", err)
	}
	css, err := os.ReadFile(tmp.Name())
	if err != nil {
		return err
	}
	out := append([]byte(header), renameVars(css, renames)...)
	return os.WriteFile(outputFile, out, 0o644)
}

// renameVars prefixes each custom property in names with "wui-" (--border becomes
// --wui-border), in declarations and var() references alike. Longer names that
// merely start with one (--border-control) are left alone.
func renameVars(css []byte, names []string) []byte {
	for _, name := range names {
		re := regexp.MustCompile(regexp.QuoteMeta(name) + `([^\w-]|$)`)
		css = re.ReplaceAll(css, []byte("--wui-"+name[2:]+"$1"))
	}
	return css
}

// platformAsset names the release binary for this system, e.g. "macos-arm64".
func platformAsset(goos, goarch string) (string, error) {
	osName := map[string]string{"darwin": "macos", "linux": "linux"}[goos]
	arch := map[string]string{"arm64": "arm64", "amd64": "x64"}[goarch]
	key := osName + "-" + arch
	if _, ok := tailwindSHA256[key]; !ok || osName == "" || arch == "" {
		return "", fmt.Errorf("no pinned Tailwind CLI for %s/%s; pass -tailwind", goos, goarch)
	}
	return key, nil
}

// ensureTailwind returns the cached, verified CLI, downloading it the first time.
func ensureTailwind() (string, error) {
	asset, err := platformAsset(runtime.GOOS, runtime.GOARCH)
	if err != nil {
		return "", err
	}
	path := filepath.Join(".task", "bin", "tailwindcss-"+tailwindVersion+"-"+asset)
	if data, err := os.ReadFile(path); err == nil && checksum(data) == tailwindSHA256[asset] {
		return path, nil
	}
	url := fmt.Sprintf("https://github.com/tailwindlabs/tailwindcss/releases/download/v%s/tailwindcss-%s", tailwindVersion, asset)
	fmt.Fprintln(os.Stderr, "wuicss: downloading", url)
	data, err := download(url)
	if err != nil {
		return "", err
	}
	if got := checksum(data); got != tailwindSHA256[asset] {
		return "", fmt.Errorf("checksum mismatch for %s: got %s", url, got)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(path, data, 0o755); err != nil {
		return "", err
	}
	return path, nil
}

func download(url string) ([]byte, error) {
	client := &http.Client{Timeout: 5 * time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	var buf bytes.Buffer
	// The CLI is about 100 MB; anything far larger is not what we pinned.
	if _, err := io.Copy(&buf, io.LimitReader(resp.Body, 400<<20)); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func checksum(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}
