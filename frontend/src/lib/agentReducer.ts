// Pure reducer turning agent session events into a chat transcript.

export interface Diff {
  path: string
  oldText: string
  newText: string
}

export interface ToolCall {
  id: string
  title?: string
  kind?: string
  status?: string
  paths?: string[]
  input?: string
  output?: string
  diffs?: Diff[]
}

export interface PlanEntry {
  content: string
  status: string
  priority?: string
}

export interface PermissionOption {
  id: string
  name: string
  kind: string
}

export interface PermissionRequest {
  id: string
  toolCall: ToolCall
  options: PermissionOption[]
}

export interface Usage {
  inputTokens: number
  outputTokens: number
  costUsd: number
}

/** Mirrors Go's agentsession.Event (an event payload, so not generated by Wails). */
export interface AgentEvent {
  sessionId: string
  seq?: number
  kind: string
  text?: string
  toolCall?: ToolCall
  plan?: PlanEntry[]
  permission?: PermissionRequest
  requestId?: string
  stopReason?: string
  usage?: Usage
}

export interface Attachment {
  path: string
  text?: string
  startLine?: number
  endLine?: number
}

export type ChatItem =
  | { type: 'user'; text: string; attachments: Attachment[] }
  | { type: 'assistant'; text: string }
  | { type: 'thought'; text: string }
  | { type: 'tool'; call: ToolCall }
  | { type: 'permission'; request: PermissionRequest; answer: string | null; settled: boolean }
  | { type: 'error'; text: string }
  | { type: 'end'; stopReason: string; usage?: Usage }

export interface ChatState {
  items: ChatItem[]
  plan: PlanEntry[]
  busy: boolean
  usage?: Usage
}

export const emptyChat: ChatState = { items: [], plan: [], busy: false }

/** Appends the user's message and marks the session busy. */
export function addUserMessage(state: ChatState, text: string, attachments: Attachment[]): ChatState {
  return { ...state, busy: true, items: [...state.items, { type: 'user', text, attachments }] }
}

/** Applies one event; returns the same object when nothing changed. */
export function applyEvent(state: ChatState, e: AgentEvent): ChatState {
  switch (e.kind) {
    case 'message_chunk':
      return appendText(state, 'assistant', e.text ?? '')
    case 'thought_chunk':
      return appendText(state, 'thought', e.text ?? '')
    case 'user_message':
      return state // our own messages are already in the transcript
    case 'tool_call':
      return e.toolCall ? upsertTool(state, e.toolCall) : state
    case 'tool_call_update':
      return e.toolCall ? upsertTool(state, e.toolCall) : state
    case 'plan':
      return { ...state, plan: e.plan ?? [] }
    case 'permission_request':
      if (!e.permission) return state
      return { ...state, items: [...state.items, { type: 'permission', request: e.permission, answer: null, settled: false }] }
    case 'permission_settled':
      return {
        ...state,
        items: state.items.map((it) =>
          it.type === 'permission' && it.request.id === e.requestId ? { ...it, settled: true } : it,
        ),
      }
    case 'usage':
      return e.usage ? { ...state, usage: e.usage } : state
    case 'error':
      return { ...state, items: [...state.items, { type: 'error', text: e.text ?? 'Unknown error' }] }
    case 'turn_end': {
      const stopReason = e.stopReason ?? 'end_turn'
      const items: ChatItem[] = [...state.items, { type: 'end', stopReason, usage: state.usage }]
      // A cancelled or failed turn leaves no request answerable.
      return { ...state, busy: false, items: stopReason === 'end_turn' ? items : settleAll(items) }
    }
  }
  return state
}

/** Records the user's answer to a permission request (before the agent confirms). */
export function answerPermission(state: ChatState, requestId: string, optionName: string): ChatState {
  return {
    ...state,
    items: state.items.map((it) =>
      it.type === 'permission' && it.request.id === requestId ? { ...it, answer: optionName, settled: true } : it,
    ),
  }
}

function appendText(state: ChatState, type: 'assistant' | 'thought', text: string): ChatState {
  if (!text) return state
  const last = state.items[state.items.length - 1]
  if (last && last.type === type) {
    const items = state.items.slice(0, -1)
    return { ...state, items: [...items, { type, text: last.text + text }] }
  }
  return { ...state, items: [...state.items, { type, text }] }
}

/** Merges a tool call or update into the existing entry with the same id. */
function upsertTool(state: ChatState, call: ToolCall): ChatState {
  const idx = state.items.findIndex((it) => it.type === 'tool' && it.call.id === call.id)
  if (idx < 0) return { ...state, items: [...state.items, { type: 'tool', call }] }
  const prev = state.items[idx] as { type: 'tool'; call: ToolCall }
  // Updates only carry what changed: keep earlier values for empty fields.
  const changed = Object.fromEntries(
    Object.entries(call).filter(([, v]) => v !== undefined && v !== '' && !(Array.isArray(v) && v.length === 0)),
  )
  const merged: ToolCall = { ...prev.call, ...changed }
  const items = state.items.slice()
  items[idx] = { type: 'tool', call: merged }
  return { ...state, items }
}

function settleAll(items: ChatItem[]): ChatItem[] {
  return items.map((it) => (it.type === 'permission' && !it.settled ? { ...it, settled: true } : it))
}

/** Files edited during the conversation (for the "changed files" summary). */
export function editedFiles(state: ChatState): string[] {
  const files = new Set<string>()
  for (const it of state.items) {
    if (it.type !== 'tool' || it.call.status === 'failed') continue
    for (const d of it.call.diffs ?? []) files.add(d.path)
    if (it.call.kind === 'edit') for (const p of it.call.paths ?? []) files.add(p)
  }
  return [...files]
}
