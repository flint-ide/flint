// Pure reducer turning agent session events into a chat transcript.

export interface Diff {
  path: string
  oldText: string
  newText: string
}

export interface ToolCall {
  id: string
  title?: string
  kind?: string
  status?: string
  paths?: string[]
  input?: string
  output?: string
  diffs?: Diff[]
}

export interface PlanEntry {
  content: string
  status: string
  priority?: string
}

export interface PermissionOption {
  id: string
  name: string
  kind: string
}

export interface PermissionRequest {
  id: string
  toolCall: ToolCall
  options: PermissionOption[]
}

export interface Usage {
  inputTokens: number
  outputTokens: number
  costUsd: number
  /** Context fill after the turn (last model call's input incl. cache) and the model's limit; 0/absent when unknown. */
  contextTokens?: number
  contextWindow?: number
}

/** Usage accumulated over a chat's turns; context is the latest turn's fill. */
export interface UsageTotals {
  inputTokens: number
  outputTokens: number
  costUsd: number
  contextTokens: number
  contextWindow: number
}

export const zeroTotals: UsageTotals = { inputTokens: 0, outputTokens: 0, costUsd: 0, contextTokens: 0, contextWindow: 0 }

/** Folds one turn's usage into the running totals (missing fields count as zero). */
export function addUsage(totals: UsageTotals | undefined, u: Usage): UsageTotals {
  const t = totals ?? zeroTotals
  return {
    inputTokens: t.inputTokens + (u.inputTokens || 0),
    outputTokens: t.outputTokens + (u.outputTokens || 0),
    costUsd: t.costUsd + (u.costUsd || 0),
    // A turn that did not report its context keeps the previous reading.
    contextTokens: u.contextTokens || t.contextTokens,
    contextWindow: u.contextWindow || t.contextWindow,
  }
}

/** Mirrors Go's agentsession.Event (an event payload, so not generated by Wails). */
export interface AgentEvent {
  sessionId: string
  seq?: number
  kind: string
  text?: string
  toolCall?: ToolCall
  plan?: PlanEntry[]
  permission?: PermissionRequest
  requestId?: string
  stopReason?: string
  usage?: Usage
}

export interface Attachment {
  path: string
  text?: string
  startLine?: number
  endLine?: number
}

export type ChatItem =
  | { type: 'user'; text: string; attachments: Attachment[] }
  | { type: 'assistant'; text: string }
  | { type: 'thought'; text: string }
  | { type: 'tool'; call: ToolCall }
  | { type: 'permission'; request: PermissionRequest; answer: string | null; settled: boolean }
  | { type: 'error'; text: string }
  | { type: 'end'; stopReason: string; usage?: Usage }

export interface ChatState {
  items: ChatItem[]
  plan: PlanEntry[]
  busy: boolean
  /** Usage of the turn in progress (becomes the `end` item's usage). */
  usage?: Usage
  /** Cumulative usage; absent in chats saved before it existed. */
  totals?: UsageTotals
}

export const emptyChat: ChatState = { items: [], plan: [], busy: false }

/** Status given to tool calls a turn left unfinished (cancelled, failed or restored). */
export const STOPPED_TOOL_STATUS = 'cancelled'

/** Appends the user's message and marks the session busy. */
export function addUserMessage(state: ChatState, text: string, attachments: Attachment[]): ChatState {
  return { ...state, busy: true, items: [...state.items, { type: 'user', text, attachments }] }
}

/** Applies one event; returns the same object when nothing changed. */
export function applyEvent(state: ChatState, e: AgentEvent): ChatState {
  switch (e.kind) {
    case 'message_chunk':
      return appendText(state, 'assistant', e.text ?? '')
    case 'thought_chunk':
      return appendText(state, 'thought', e.text ?? '')
    case 'user_message':
      return state // our own messages are already in the transcript
    case 'tool_call':
      return e.toolCall ? upsertTool(state, e.toolCall) : state
    case 'tool_call_update':
      return e.toolCall ? upsertTool(state, e.toolCall) : state
    case 'plan':
      return { ...state, plan: e.plan ?? [] }
    case 'permission_request':
      if (!e.permission) return state
      return { ...state, items: [...state.items, { type: 'permission', request: e.permission, answer: null, settled: false }] }
    case 'permission_settled':
      return {
        ...state,
        items: state.items.map((it) =>
          it.type === 'permission' && it.request.id === e.requestId ? { ...it, settled: true } : it,
        ),
      }
    case 'usage':
      return e.usage ? { ...state, usage: e.usage, totals: addUsage(state.totals, e.usage) } : state
    case 'error':
      return { ...state, items: [...state.items, { type: 'error', text: e.text ?? 'Unknown error' }] }
    case 'turn_end': {
      const stopReason = e.stopReason ?? 'end_turn'
      const items: ChatItem[] = [...state.items, { type: 'end', stopReason, usage: state.usage }]
      // A cancelled or failed turn leaves no request answerable and no tool running.
      return { ...state, busy: false, usage: undefined, items: stopReason === 'end_turn' ? items : settleItems(items) }
    }
  }
  return state
}

/**
 * Applies events in order. Consecutive chunks of the same kind are joined first, so
 * a batch of streamed tokens copies the transcript once per run of text, not per token.
 */
export function applyEvents(state: ChatState, events: readonly AgentEvent[]): ChatState {
  let next = state
  for (let i = 0; i < events.length; i++) {
    const e = events[i]
    if (e.kind !== 'message_chunk' && e.kind !== 'thought_chunk') {
      next = applyEvent(next, e)
      continue
    }
    let text = e.text ?? ''
    while (i + 1 < events.length && events[i + 1].kind === e.kind) text += events[++i].text ?? ''
    next = applyEvent(next, { ...e, text })
  }
  return next
}

/** Records the user's answer to a permission request (before the agent confirms). */
export function answerPermission(state: ChatState, requestId: string, optionName: string): ChatState {
  return {
    ...state,
    items: state.items.map((it) =>
      it.type === 'permission' && it.request.id === requestId ? { ...it, answer: optionName, settled: true } : it,
    ),
  }
}

function appendText(state: ChatState, type: 'assistant' | 'thought', text: string): ChatState {
  if (!text) return state
  const lastIdx = state.items.length - 1
  const last = state.items[lastIdx]
  if (last && last.type === type) {
    const items = state.items.slice() // one copy per chunk: the transcript can be long
    items[lastIdx] = { type, text: last.text + text }
    return { ...state, items }
  }
  return { ...state, items: [...state.items, { type, text }] }
}

/** Merges a tool call or update into the existing entry with the same id. */
function upsertTool(state: ChatState, call: ToolCall): ChatState {
  // Updates are for recent calls: search from the end.
  const idx = state.items.findLastIndex((it) => it.type === 'tool' && it.call.id === call.id)
  if (idx < 0) return { ...state, items: [...state.items, { type: 'tool', call }] }
  const prev = state.items[idx] as { type: 'tool'; call: ToolCall }
  // Updates only carry what changed: keep earlier values for empty fields.
  const changed = Object.fromEntries(
    Object.entries(call).filter(([, v]) => v !== undefined && v !== '' && !(Array.isArray(v) && v.length === 0)),
  )
  const merged: ToolCall = { ...prev.call, ...changed }
  const items = state.items.slice()
  items[idx] = { type: 'tool', call: merged }
  return { ...state, items }
}

/**
 * Closes what an ended turn left open: unanswered questions expire and tool calls still
 * pending or running are marked stopped. Returns the same array when nothing was open.
 */
export function settleItems(items: ChatItem[]): ChatItem[] {
  let changed = false
  const settled = items.map((it): ChatItem => {
    if (it.type === 'permission' && !it.settled) {
      changed = true
      return { ...it, settled: true }
    }
    if (it.type === 'tool' && isRunning(it.call.status)) {
      changed = true
      return { ...it, call: { ...it.call, status: STOPPED_TOOL_STATUS } }
    }
    return it
  })
  return changed ? settled : items
}

/** A missing status renders as pending, so it counts as running too. */
const isRunning = (status?: string) => !status || status === 'pending' || status === 'in_progress'

/** Files edited during the conversation (for the "changed files" summary). */
export function editedFiles(state: ChatState): string[] {
  const files = new Set<string>()
  for (const it of state.items) {
    if (it.type !== 'tool' || it.call.status === 'failed') continue
    for (const d of it.call.diffs ?? []) files.add(d.path)
    if (it.call.kind === 'edit') for (const p of it.call.paths ?? []) files.add(p)
  }
  return [...files]
}
