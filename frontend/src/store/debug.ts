// One debug session at a time (Go via Delve), shown in the "debug" tab: the
// adapter's events drive it, requests go through DebugAPI.

export type DebugStatus = 'starting' | 'running' | 'paused' | 'ended'
export type DebugStep = 'continue' | 'next' | 'stepIn' | 'stepOut' | 'pause'

export interface DebugSession {
  /** Process id given to DebugAPI; a restart gets a new one so late events are dropped. */
  id: string
  title: string
  status: DebugStatus
  /** Why it stopped (breakpoint, step, pause, exception…) and the adapter's note. */
  stopReason?: string
  stopText?: string
  threadId: number
  frames: dap.StackFrame[]
  frameId: number
  scopes: dap.Scope[]
  /** Children by variablesReference, loaded on expand. */
  vars: Record<number, dap.Variable[]>
  expanded: Record<number, boolean>
  restart: () => Promise<void>
}

/** Bodies of the adapter events used here (event payloads, not generated by Wails). */
interface StoppedEvent {
  reason: string
  threadId?: number
  text?: string
}
interface OutputEvent {
  category?: string
  output: string
}

interface DebugState {
  breakpoints: BreakpointMap
  session: DebugSession | null
  /** Console of the session: program output, adapter messages and evaluations.
   * Kept apart from session so streaming output doesn't re-render frames and variables. */
  output: string
}

export const DEBUG_TAB = 'debug'
const OUTPUT_LIMIT = 100_000

export const useDebug = createStore<DebugState>(() => ({ breakpoints: {}, session: null, output: '' }))

/** Where the paused program is, for the editor's current-line highlight. */
export function pausedAt(s: DebugState = useDebug.getState()): { path: string; line: number } | null {
  const session = s.session
  if (session?.status !== 'paused') return null
  const frame = session.frames.find((f) => f.id === session.frameId) ?? session.frames[0]
  return frame?.source?.path ? { path: frame.source.path, line: frame.line } : null
}

export const isDebugging = () => {
  const status = useDebug.getState().session?.status
  return status === 'running' || status === 'paused' || status === 'starting'
}
export const isPaused = () => useDebug.getState().session?.status === 'paused'

// ---------- breakpoints ----------

export function toggleBreakpoint(path: string, line: number): void {
  useDebug.setState((s) => ({ breakpoints: toggleLine(s.breakpoints, path, line) }))
  void syncBreakpoints(path)
}

/** Lines moved by edits in the editor. */
export function moveBreakpoints(path: string, lines: number[]): void {
  const before = useDebug.getState().breakpoints
  const after = withLines(before, path, lines)
  if (after === before) return
  useDebug.setState({ breakpoints: after })
  void syncBreakpoints(path)
}

export function setAllBreakpoints(map: BreakpointMap): void {
  useDebug.setState({ breakpoints: map })
}

/** ⌘F8 on the cursor line of the active editor. */
export function toggleBreakpointAtCursor(): void {
  const { tabs, activeId } = useEditor.getState()
  const tab = tabs.find((t) => t.id === activeId)
  if (tab?.kind !== 'file') return
  const view = viewFor(tab.id)
  if (!view) return
  toggleBreakpoint(tab.path, view.state.doc.lineAt(view.state.selection.main.head).number)
}

/** What the editor's breakpoint gutter needs from this store. */
export const breakpointHooks: BreakpointHooks = {
  lines: (path) => useDebug.getState().breakpoints[path] ?? [],
  toggle: toggleBreakpoint,
  moved: moveBreakpoints,
  pausedLine: (path) => {
    const at = pausedAt()
    return at?.path === path ? at.line : null
  },
  // Not on every session change: program output streams through the session.
  subscribe: (listener) =>
    useDebug.subscribe((s, prev) => {
      if (s.breakpoints !== prev.breakpoints || pausedKey(s) !== pausedKey(prev)) listener()
    }),
}

const pausedKey = (s: DebugState) => {
  const at = pausedAt(s)
  return at ? `${at.path}:${at.line}` : ''
}

async function syncBreakpoints(path: string): Promise<void> {
  const session = useDebug.getState().session
  if (!session || session.status === 'ended' || session.status === 'starting') return
  const lines = useDebug.getState().breakpoints[path] ?? []
  try {
    await DebugAPI.SetBreakpoints(session.id, path, lines.map((line) => dap.SourceBreakpoint.createFrom({ line })))
  } catch (err) {
    showToast(`Breakpoint: ${errorMessage(err)}`, 'error')
  }
}

const launchBreakpoints = () =>
  Object.fromEntries(
    Object.entries(useDebug.getState().breakpoints).map(([path, lines]) => [path, lines.map((line) => dap.SourceBreakpoint.createFrom({ line }))]),
  )

// ---------- sessions ----------

/** Debugs the selected run configuration (⌃D). */
export function debugSelected(): Promise<void> {
  const config = selectedRunConfig()
  if (!config) {
    showToast('Select a Go run configuration to debug')
    return Promise.resolve()
  }
  return debugConfiguration(config)
}

export function canDebug(config: RunConfig | null = selectedRunConfig()): boolean {
  return !!config && !!useRun.getState().capabilities[config.id]?.debug
}

/** Debugs config of root (default: the folder whose configurations are shown). */
export function debugConfiguration(config: RunConfig, root: string | null = useRun.getState().root): Promise<void> {
  if (!root) return Promise.resolve()
  if (!canDebug(config)) {
    showToast(`${config.name} can't be debugged (only Go configurations)`)
    return Promise.resolve()
  }
  const run = () => start(`Debug ${config.name}`, (id) => DebugAPI.Start(id, root, config, launchBreakpoints()), run)
  return run()
}

/** Debugs Go tests of the package in dir (all, or the named ones). */
export function debugTests(dir: string, tests: string[], title: string): Promise<void> {
  const run = () => start(`Debug ${title}`, (id) => DebugAPI.StartTest(id, dir, tests, launchBreakpoints()), run)
  return run()
}

const dirOf = (path: string) => path.slice(0, path.lastIndexOf('/'))
const baseOf = (path: string) => path.slice(path.lastIndexOf('/') + 1)

/** Debugs one Go test (a subtest's full name works too). */
export function debugTestAt(path: string, name: string): Promise<void> {
  return debugTests(dirOf(path), [name], name)
}

/** Debugs the tests of one Go file (its top-level tests; the package when none are found). */
export async function debugTestsInFile(path: string): Promise<void> {
  const view = viewFor(fileTabId(path))
  const content = view?.state.doc.toString() ?? ''
  const marks = ((await RunAPI.TestMarks(path, content).catch(() => [])) ?? []) as TestMark[]
  const names = marks.filter((m) => m.kind === 'test').map((m) => m.name)
  return debugTests(dirOf(path), names, baseOf(path))
}

/** Test gutter shift-click: debug instead of run (Go only). */
export function debugTestMark(path: string, mark: TestMark): void {
  void (mark.kind === 'file' ? debugTestsInFile(path) : debugTestAt(path, mark.name))
}

async function start(title: string, launch: (id: string) => Promise<void>, restart: () => Promise<void>): Promise<void> {
  const prev = useDebug.getState().session
  if (prev && prev.status !== 'ended') await DebugAPI.Stop(prev.id).catch(() => undefined)
  if (prev) deliverDebug?.forget(prev.id) // every session has its own id; drop the old one's ordering state
  const id = crypto.randomUUID()
  useDebug.setState({
    session: { id, title, status: 'starting', threadId: 0, frames: [], frameId: 0, scopes: [], vars: {}, expanded: {}, restart },
    output: `Building and starting ${title.replace(/^Debug /, '')}…\n`,
  })
  useEditor.getState().openDebug(title)
  try {
    await launch(id)
    update(id, (s) => (s.status === 'starting' ? { status: 'running' } : {}))
  } catch (err) {
    update(id, () => ({ status: 'ended' }))
    print(id, `${errorMessage(err)}\n`)
  }
}

export async function stopDebug(): Promise<void> {
  const s = useDebug.getState().session
  if (s && s.status !== 'ended') await DebugAPI.Stop(s.id).catch(() => undefined)
}

export async function restartDebug(): Promise<void> {
  await useDebug.getState().session?.restart()
}

export async function debugStep(action: DebugStep): Promise<void> {
  const s = useDebug.getState().session
  if (!s || s.status === 'ended' || s.status === 'starting') return
  if (action !== 'pause' && s.status !== 'paused') return
  try {
    await DebugAPI.Step(s.id, action, s.threadId || 1)
  } catch (err) {
    showToast(errorMessage(err), 'error')
  }
}

/** Shows a frame: its source in the editor and its variables. */
export async function selectFrame(frameId: number): Promise<void> {
  const s = useDebug.getState().session
  const frame = s?.frames.find((f) => f.id === frameId)
  if (!s || !frame) return
  update(s.id, () => ({ frameId, scopes: [], vars: {}, expanded: {} }))
  if (frame.source?.path) useEditor.getState().openFile(frame.source.path, { line: frame.line, from: 0, to: 0 })
  try {
    const scopes = (await DebugAPI.Scopes(s.id, frameId)) ?? []
    update(s.id, () => ({ scopes }))
    const first = scopes.find((sc) => !sc.expensive)
    if (first) await toggleVariable(first.variablesReference)
  } catch (err) {
    showToast(errorMessage(err), 'error')
  }
}

/** Expands or collapses a scope or structured variable. */
export async function toggleVariable(ref: number): Promise<void> {
  const s = useDebug.getState().session
  if (!s || ref <= 0) return
  const open = !s.expanded[ref]
  update(s.id, (cur) => ({ expanded: { ...cur.expanded, [ref]: open } }))
  if (!open || s.vars[ref]) return
  try {
    const vars = (await DebugAPI.Variables(s.id, ref)) ?? []
    update(s.id, (cur) => ({ vars: { ...cur.vars, [ref]: vars } }))
  } catch (err) {
    update(s.id, (cur) => ({ vars: { ...cur.vars, [ref]: [] } }))
    print(s.id, `${errorMessage(err)}\n`)
  }
}

/** Evaluates an expression in the selected frame and prints it to the console. */
export async function evaluate(expr: string): Promise<void> {
  const s = useDebug.getState().session
  if (!s || s.status === 'ended' || !expr.trim()) return
  let line: string
  try {
    const res = await DebugAPI.Evaluate(s.id, expr, s.status === 'paused' ? s.frameId : 0)
    line = `${expr} = ${res.result}${res.type ? ` (${res.type})` : ''}`
  } catch (err) {
    line = `${expr}: ${errorMessage(err)}`
  }
  print(s.id, `› ${line}\n`)
}

function update(id: string, fn: (s: DebugSession) => Partial<DebugSession>): void {
  useDebug.setState((st) => {
    if (st.session?.id !== id) return {}
    return { session: { ...st.session, ...fn(st.session) } }
  })
}

// A chatty program would re-render the console per line; output is folded in
// at most once per frame.
let queued: { id: string; text: string } | null = null
function queueOutput(id: string, text: string): void {
  if (queued && queued.id !== id) flushOutput()
  if (queued) {
    queued.text += text
    return
  }
  queued = { id, text }
  requestAnimationFrame(flushOutput)
}
function flushOutput(): void {
  if (!queued) return
  const { id, text } = queued
  queued = null
  print(id, text)
}

/** Appends to the console of session id, keeping its last OUTPUT_LIMIT characters. */
function print(id: string, text: string): void {
  useDebug.setState((st) => {
    if (st.session?.id !== id) return {}
    const next = st.output + text
    return { output: next.length > OUTPUT_LIMIT ? next.slice(next.length - OUTPUT_LIMIT) : next }
  })
}

/** The adapter stopped the program: load the stack and show the top frame. */
async function onStopped(id: string, body: StoppedEvent): Promise<void> {
  const threadId = body.threadId || useDebug.getState().session?.threadId || 1
  update(id, () => ({ status: 'paused', stopReason: body.reason, stopText: body.text, threadId, frames: [] }))
  try {
    const frames = (await DebugAPI.StackTrace(id, threadId)) ?? []
    if (useDebug.getState().session?.status !== 'paused') return // resumed meanwhile
    update(id, () => ({ frames }))
    // Skip runtime frames without source (e.g. a pause inside the scheduler).
    const top = frames.find((f) => f.source?.path) ?? frames[0]
    if (top) await selectFrame(top.id)
  } catch (err) {
    print(id, `${errorMessage(err)}\n`)
  }
}

// ---------- events ----------

interface DebugEventMsg {
  id: string
  seq?: number
  name: string
  body?: unknown
}

let deliverDebug: Reorderer<DebugEventMsg> | null = null

let subscribed = false
export function subscribeDebugEvents(): void {
  if (subscribed) return
  subscribed = true
  const deliver: Reorderer<DebugEventMsg> = createReorderer<DebugEventMsg>((id, ev) => {
    if (useDebug.getState().session?.id !== id) return // replaced by a restart
    if (ev.name !== 'output') flushOutput() // keep output before what follows it
    switch (ev.name) {
      case 'stopped':
        void onStopped(id, ev.body as StoppedEvent)
        break
      case 'continued':
        update(id, () => ({ status: 'running', frames: [], scopes: [], vars: {}, expanded: {} }))
        break
      case 'output': {
        const out = ev.body as OutputEvent
        if (out?.output && out.category !== 'telemetry') queueOutput(id, out.output)
        break
      }
      case 'exited': {
        const code = (ev.body as { exitCode?: number })?.exitCode
        print(id, `\nProcess finished with exit code ${code ?? '?'}\n`)
        break
      }
      case 'terminated':
      case 'ended':
        update(id, () => ({ status: 'ended', frames: [], scopes: [], vars: {}, expanded: {} }))
        break
    }
  })
  deliverDebug = deliver
  EventsOn('debug:event', (ev: DebugEventMsg) => deliver(ev.id, ev))
}
